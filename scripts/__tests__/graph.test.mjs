import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import { readLayout } from '../../packages/eslint-config/src/layout.utils.js';
import { copiedGraphProblems, graphBlock, graphEdges, graphProblem, withGraph } from '../graph.mjs';
import { createTempRepo, REPO_ROOT, removeTempRepos } from './temp-repo.utils.mjs';

afterEach(removeTempRepos);

const entry = (fields) => ({ kind: 'package', domain: 'generic', dependsOn: [], ...fields });
const LAYOUT = {
  '@sheavly/base': entry({}),
  '@sheavly/mid': entry({ dependsOn: ['@sheavly/base'] }),
  '@sheavly/top': entry({ domain: 'coding', dependsOn: ['@sheavly/mid', '@sheavly/base'] }),
  '@sheavly/lint': entry({ domain: 'tooling' }),
  '@sheavly/cli': entry({ kind: 'app', domain: 'coding', dependsOn: ['@sheavly/top'] }),
};
const MARKERS =
  '# Overview\n\n<!-- graph:start (generated by `npm run graph`; do not edit) -->\n<!-- graph:end -->\n';

describe('the workspace graph', () => {
  it('draws an edge only where no other dependency already reaches it', () => {
    expect(graphEdges(LAYOUT)).toEqual([
      ['@sheavly/cli', '@sheavly/top'],
      ['@sheavly/mid', '@sheavly/base'],
      ['@sheavly/top', '@sheavly/mid'],
    ]);
  });

  it('groups generic and coding packages and apps, and leaves tooling out', () => {
    const block = graphBlock(LAYOUT);

    expect(block).toContain('subgraph group_coding ["coding packages"]');
    expect(block).toContain('cli["@sheavly/cli"]');
    expect(block).not.toContain('lint');
  });

  it('draws the launcher, which is named without the scope, with a node of its own', () => {
    const layout = {
      ...LAYOUT,
      sheavly: entry({
        kind: 'app',
        domain: 'coding',
        launcher: true,
        dependsOn: ['@sheavly/cli'],
      }),
    };
    const block = graphBlock(layout);

    expect(block).toContain('sheavly["sheavly"]');
    expect(block).toContain('sheavly --> cli');
    expect(block).not.toMatch(/^\s+\["/m);
    expect(block).not.toMatch(/^\s+-->/m);
  });

  it('fails a diagram that no longer matches the workspaces, and one with no markers', () => {
    const root = createTempRepo({
      'package.json': JSON.stringify({ name: 'monorepo', workspaces: ['packages/*'] }),
      'packages/base/package.json': JSON.stringify({
        name: '@sheavly/base',
        sheavly: { domain: 'generic' },
      }),
      'docs/overview.md': MARKERS,
      'docs/README.md':
        '<!-- workspaces:start (generated by `npm run graph`; do not edit) -->\n<!-- workspaces:end -->\n',
    });
    const file = path.join(root, 'docs/overview.md');

    expect(graphProblem(root)).toContain('out of date');

    writeFileSync(file, withGraph({ markdown: MARKERS, block: graphBlock(readLayout({ root })) }));
    expect(graphProblem(root)).toBeNull();

    writeFileSync(file, '# Overview\n');
    expect(graphProblem(root)).toContain('the markers for the workspace graph are missing');
  });

  it('fails a doc that draws its own copy of the graph', () => {
    const root = createTempRepo({
      'README.md': '```\n@sheavly/protocol  ←  @sheavly/core\n```\n',
      'docs/notes.md': 'see [the graph](overview.md#layers)\n',
    });

    expect(copiedGraphProblems({ root, files: ['README.md', 'docs/notes.md'] })).toEqual([
      expect.stringContaining('README.md: draws the workspace graph by hand'),
    ]);
  });

  it("is current in this repo's overview", () => {
    expect(graphProblem(REPO_ROOT)).toBeNull();
    expect(readFileSync(path.join(REPO_ROOT, 'docs/overview.md'), 'utf8')).toContain(
      '"@sheavly/terminal"',
    );
  });
});
