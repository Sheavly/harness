// What the docs say about the workspaces, generated from the workspaces themselves (`readLayout`
// and each one's package.json), so it can't drift from the code: the graph in `docs/overview.md`,
// the workspace index in `docs/README.md` and the router skill's table
// (`.agents/skills/sheavly-packages/`), each between two markers. The layout check
// (`npm run layout`) fails when one is out of date, and `npm run graph` rewrites them.
//
//   npm run graph   rewrite the generated blocks
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { readLayout } from '../packages/eslint-config/src/layout.utils.js';

export const GRAPH_DOC = 'docs/overview.md';
const INDEX_DOC = 'docs/README.md';

export const ROUTER_SKILL = '.agents/skills/sheavly-packages/SKILL.md';
/** Every doc `npm run graph` writes, all drawn from the workspaces' package.json. */
export const GENERATED_DOCS = [GRAPH_DOC, INDEX_DOC, ROUTER_SKILL];
const markers = (name) => ({
  start: `<!-- ${name}:start (generated by \`npm run graph\`; do not edit) -->`,
  end: `<!-- ${name}:end -->`,
});
const GRAPH = markers('graph');
const INDEX = markers('workspaces');
const ROUTER = markers('packages');
const { start: START, end: END } = GRAPH;
const SCOPE = '@sheavly/';
const GROUPS = [
  {
    id: 'generic',
    title: 'generic packages',
    match: (entry) => entry.kind !== 'extension' && entry.domain === 'generic',
  },
  {
    id: 'coding',
    title: 'coding packages',
    match: (entry) => entry.kind === 'package' && entry.domain === 'coding',
  },
  { id: 'extensions', title: 'extensions', match: (entry) => entry.kind === 'extension' },
  { id: 'apps', title: 'apps', match: (entry) => entry.kind === 'app' },
];

// The launcher is the one workspace named without the scope (`sheavly`): its name is its short name.
const short = (name) => (name.startsWith(SCOPE) ? name.slice(SCOPE.length) : name);
const nodeId = (name) => short(name).replaceAll('-', '_');

/** Everything `name` reaches through its runtime dependencies, itself excluded. */
function reachable(params) {
  const { layout, name } = params;
  const seen = new Set();
  const visit = (from) => {
    for (const dep of layout[from]?.dependsOn ?? []) {
      if (!seen.has(dep)) {
        seen.add(dep);
        visit(dep);
      }
    }
  };

  visit(name);

  return seen;
}

/**
 * The edges worth drawing: `a → b` unless `a` already reaches `b` through another dependency
 * (a transitive reduction). What `a` may import is everything it reaches.
 */
export function graphEdges(layout) {
  return Object.entries(layout)
    .flatMap(([name, entry]) =>
      entry.dependsOn
        .filter((dep) =>
          entry.dependsOn.every(
            (other) => other === dep || !reachable({ layout, name: other }).has(dep),
          ),
        )
        .map((dep) => [name, dep]),
    )
    .sort(([a1, b1], [a2, b2]) => a1.localeCompare(a2) || b1.localeCompare(b2));
}

/** The diagram, as a mermaid block between the markers. Tooling and test-only ones are left out. */
export function graphBlock(layout) {
  const shown = Object.fromEntries(
    Object.entries(layout).filter(([, entry]) => entry.domain !== 'tooling' && !entry.testOnly),
  );
  const groups = GROUPS.flatMap(({ id, title, match }) => {
    const names = Object.keys(shown)
      .filter((name) => match(shown[name]))
      .sort();

    return names.length === 0
      ? []
      : [
          `  subgraph group_${id} ["${title}"]`,
          ...names.map((name) => `    ${nodeId(name)}["${name}"]`),
          '  end',
        ];
  });
  const edges = graphEdges(shown).map(([from, to]) => `  ${nodeId(from)} --> ${nodeId(to)}`);

  return [START, '', '```mermaid', 'flowchart BT', ...groups, ...edges, '```', '', END].join('\n');
}

/** `markdown` with the block between `marks` replaced by `block`; null when it has no markers. */
function withBlock(params) {
  const { markdown, block, marks = GRAPH } = params;
  const start = markdown.indexOf(marks.start);
  const end = markdown.indexOf(marks.end);

  if (start === -1 || end < start) return null;

  return markdown.slice(0, start) + block + markdown.slice(end + marks.end.length);
}

/** `markdown` with its diagram replaced by `block`; null when it has no markers. */
export function withGraph(params) {
  return withBlock(params);
}

/**
 * The workspace index: each workspace, linked to its README, with its package.json description.
 * The README is the first place to look; its docs/ folder goes deeper.
 */
export function indexBlock(params) {
  const rows = workspaceRows({ ...params, from: INDEX_DOC }).map(({ link, description }) => [
    link,
    description,
  ]);

  return [INDEX.start, '', ...table([['Workspace', 'What it is'], ...rows]), '', INDEX.end].join(
    '\n',
  );
}

/**
 * Each workspace, sorted by folder: a link to its README from the doc at `from`, its package.json
 * description (escaped for a table cell), and its layout entry.
 */
function workspaceRows(params) {
  const { root, layout, from } = params;
  const up = path.posix.relative(path.posix.dirname(from), '.');

  return Object.entries(layout)
    .sort(([, a], [, b]) => a.dir.localeCompare(b.dir))
    .map(([name, entry]) => {
      const manifest = JSON.parse(readFileSync(path.join(root, entry.dir, 'package.json'), 'utf8'));

      return {
        name,
        entry,
        link: `[\`${name}\`](${up}/${entry.dir}/README.md)`,
        description: String(manifest.description ?? '').replaceAll('|', '\\|'),
      };
    });
}

/** A markdown table padded the way Prettier pads one, so the generated block stays as written. */
function table(rows) {
  const width = (cell) => [...cell].length;
  const widths = rows[0].map((_, column) => Math.max(3, ...rows.map((row) => width(row[column]))));
  const line = (cells) =>
    `| ${cells.map((cell, column) => cell + ' '.repeat(widths[column] - width(cell))).join(' | ')} |`;

  return [line(rows[0]), line(widths.map((size) => '-'.repeat(size))), ...rows.slice(1).map(line)];
}

/** What a workspace is, in the router: its kind, and its domain or role. */
function roleOf(entry) {
  if (entry.testOnly) return 'test-only';

  return entry.kind === 'package' ? entry.domain : `${entry.kind}, ${entry.domain}`;
}

/**
 * The router skill's table: each workspace, linked to its README, with its role, its
 * package.json description and the workspaces it depends on at runtime.
 */
export function routerBlock(params) {
  const rows = workspaceRows({ ...params, from: ROUTER_SKILL }).map(
    ({ link, entry, description }) => [
      link,
      roleOf(entry),
      description,
      entry.dependsOn.map((dep) => `\`${short(dep)}\``).join(', ') || 'nothing',
    ],
  );

  return [
    ROUTER.start,
    '',
    ...table([['Workspace', 'Role', 'What it is for', 'Depends on'], ...rows]),
    '',
    ROUTER.end,
  ].join('\n');
}

/** The generated blocks, each with the doc that holds it and what goes in it. */
function generated(root) {
  const layout = readLayout({ root });

  return [
    { doc: GRAPH_DOC, marks: GRAPH, what: 'the workspace graph', block: graphBlock(layout) },
    {
      doc: INDEX_DOC,
      marks: INDEX,
      what: 'the workspace index',
      block: indexBlock({ root, layout }),
    },
    {
      doc: ROUTER_SKILL,
      marks: ROUTER,
      what: 'the workspace router',
      block: routerBlock({ root, layout }),
    },
  ];
}

/** Why a generated block in `root`'s docs isn't what the workspaces say; one problem each. */
export function generatedProblems(root) {
  return generated(root).flatMap(({ doc, marks, what, block }) => {
    if (!existsSync(path.join(root, doc))) {
      return [`${doc} is missing: it holds ${what}, generated by \`npm run graph\`.`];
    }

    const markdown = readFileSync(path.join(root, doc), 'utf8');
    const updated = withBlock({ markdown, block, marks });

    if (updated === null) {
      return [
        `${doc}: the markers for ${what} are missing; put ${marks.start} and ${marks.end} where it goes, then run \`npm run graph\`.`,
      ];
    }

    return updated === markdown
      ? []
      : [
          `${doc}: ${what} is out of date with the workspaces' package.json; run \`npm run graph\`.`,
        ];
  });
}

/** Why the diagram in `root`'s overview isn't the graph on disk, or null when it is. */
export function graphProblem(root) {
  return generatedProblems(root).find((problem) => problem.startsWith(GRAPH_DOC)) ?? null;
}

/** A hand-drawn workspace graph: an import chain (`@sheavly/a  ←  …`) or a mermaid flowchart. */
const DRAWN_GRAPH = /@sheavly\/[a-z-]+\s+←|```mermaid\s+flowchart/;

/**
 * Markdown files (of `files`, relative to `root`) that draw the workspace graph by hand: it lives
 * once, generated, in the overview, and a copy would drift from it.
 */
export function copiedGraphProblems(params) {
  const { root, files } = params;

  return files
    .filter((file) => file.endsWith('.md') && !file.startsWith('workbook/'))
    .filter((file) => {
      const markdown = readFileSync(path.join(root, file), 'utf8');
      const outside =
        file === GRAPH_DOC ? (withGraph({ markdown, block: '' }) ?? markdown) : markdown;

      return DRAWN_GRAPH.test(outside);
    })
    .map(
      (file) =>
        `${file}: draws the workspace graph by hand. Link to it instead ([the graph](${path.posix.relative(path.posix.dirname(file), GRAPH_DOC)}#layers)); it is generated there from the workspaces.`,
    );
}

if (path.resolve(process.argv[1] ?? '') === fileURLToPath(import.meta.url)) {
  const root = path.resolve(import.meta.dirname, '..');

  for (const { doc, marks, block } of generated(root)) {
    const file = path.join(root, doc);
    const updated = withBlock({ markdown: readFileSync(file, 'utf8'), block, marks });

    if (updated === null) {
      console.error(generatedProblems(root).find((problem) => problem.startsWith(doc)));
      process.exit(1);
    }

    writeFileSync(file, updated);
    console.log(`Wrote the generated block in ${doc}.`);
  }
}
