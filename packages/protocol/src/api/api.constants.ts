/** The API's OpenAPI document, committed at the package root (`npm run schema -w @sheavly/protocol`). */
export const OPENAPI_FILE = 'openapi.json';

/** The doc whose route table is generated from `API_ROUTES`, relative to the package root. */
export const ROUTE_TABLE_DOC = 'docs/contract.md';

/** The markers around the generated route table in `ROUTE_TABLE_DOC`. */
export const ROUTE_TABLE_MARKERS = {
  start: '<!-- routes:start (generated by `npm run schema -w @sheavly/protocol`; do not edit) -->',
  end: '<!-- routes:end -->',
} as const;

/** Which OpenAPI version the document is: 3.2, the first with QUERY and stream item schemas. */
export const OPENAPI_VERSION = '3.2.0';

/** The `Last-Event-ID` header a stream resumes after: the last entry's `seq` a client got. */
export const LAST_EVENT_ID_HEADER = 'Last-Event-ID';

/**
 * The SSE event name of a frame that carries an entry, as JSON: on the conversation's stream every
 * frame is one `StreamEntry`; on the channel stream it is an entry of a channel (a node's or the
 * tree's), beside the `head`, `end` and `snapshot` frames.
 */
export const ENTRY_EVENT = 'entry';

/**
 * The harness's HTTP API, by operation: every route a server implements and a client calls, with
 * the contract's schemas that validate its body and answer. The one definition of the API: the
 * server builds its routes from it, the OpenAPI document is written from it, and the client is
 * generated from that. Each route says whether it reads or changes, and `ApiRoute` holds its
 * method to that; a new one follows "A route" in `.agents/skills/sheavly/extending.md`.
 */
export const API_ROUTES = {
  listConversations: {
    effect: 'read',
    method: 'get',
    path: '/conversations',
    summary: 'Every live conversation, oldest first',
    response: { status: 200, schema: conversationsResponseSchema },
  },
  startConversation: {
    effect: 'change',
    method: 'post',
    path: '/conversations',
    summary: 'Start a conversation, empty or continuing saved messages',
    body: startConversationRequestSchema,
    response: { status: 201, schema: startConversationResponseSchema },
  },
  getConversation: {
    effect: 'read',
    method: 'get',
    path: '/conversations/{id}',
    summary: 'What the run is: workspace, models, trust, the permission mode',
    response: { status: 200, schema: conversationDetailsSchema },
  },
  closeConversation: {
    effect: 'change',
    method: 'delete',
    path: '/conversations/{id}',
    summary: 'Close it: its prompts, tasks and processes stop',
    response: { status: 204 },
  },
  switchModel: {
    effect: 'change',
    method: 'put',
    path: '/conversations/{id}/model',
    summary: 'Switch to one of its models, from the next model call',
    body: switchModelRequestSchema,
    response: { status: 204 },
  },
  getMessages: {
    effect: 'read',
    method: 'get',
    path: '/conversations/{id}/messages',
    summary: 'The history so far, valid to continue from',
    response: { status: 200, schema: messagesResponseSchema },
  },
  querySkills: {
    effect: 'read',
    method: 'query',
    path: '/conversations/{id}/skills',
    summary: 'The skills a prompt can run, all or those a search matches, for a / menu',
    body: skillsQuerySchema,
    response: { status: 200, schema: skillsResponseSchema },
  },
  sendPrompt: {
    effect: 'change',
    method: 'post',
    path: '/conversations/{id}/prompts',
    summary:
      "Send the next prompt, answered at once with the agent node that carries the run (and the message it became, for one that started): it starts, or waits in the queue while the conversation is busy; what it does arrives on the node's channel and the tree",
    body: sendPromptRequestSchema,
    response: { status: 200, schema: promptSentSchema },
  },
  yieldPrompt: {
    effect: 'change',
    method: 'post',
    path: '/conversations/{id}/yield',
    summary:
      'Ask the running prompt to end at its completion point without waiting for background work; nothing is interrupted or steered',
    response: { status: 200, schema: yieldPromptResponseSchema },
  },
  getQueue: {
    effect: 'read',
    method: 'get',
    path: '/conversations/{id}/queue',
    summary:
      'The lines waiting to start, kept across a restart; reopening starts none of them until the next line is sent',
    response: { status: 200, schema: queuedPromptsSchema },
  },
  setQueue: {
    effect: 'change',
    method: 'put',
    path: '/conversations/{id}/queue',
    summary: 'Replace the queued lines; they stay outside history, model input and summaries',
    body: queuedPromptsSchema,
    response: { status: 204 },
  },
  stopPrompt: {
    effect: 'change',
    method: 'post',
    path: '/conversations/{id}/stop',
    summary: 'Stop the running prompt; history stays valid',
    response: { status: 204 },
  },
  cancelNode: {
    effect: 'change',
    method: 'post',
    path: '/conversations/{id}/nodes/{node}/cancel',
    summary:
      'Cancel one node, whatever its kind: a command or service is killed, a sub-agent stopped, the main agent as stop does; a node that has ended is node_ended',
    response: { status: 204 },
  },
  messageNode: {
    effect: 'change',
    method: 'post',
    path: '/conversations/{id}/nodes/{node}/messages',
    summary:
      'Send a message to an agent node, which sees it at its next model call; only the main agent takes one from the user, and a node that has ended is node_ended',
    body: messageNodeRequestSchema,
    response: { status: 204 },
  },
  answerApproval: {
    effect: 'change',
    method: 'post',
    path: '/conversations/{id}/approvals/{approval}',
    summary: 'Answer a waiting approval',
    body: answerApprovalRequestSchema,
    response: { status: 204 },
  },
  streamConversation: {
    effect: 'read',
    method: 'query',
    path: '/conversations/{id}/stream',
    summary: 'Follow the whole conversation: every entry, filtered, while the client stays',
    body: streamQuerySchema,
    response: { status: 200, stream: streamEntrySchema, resumesWithLastEventId: true },
  },
  streamChannels: {
    effect: 'read',
    method: 'query',
    path: '/conversations/{id}/subscribe',
    summary:
      "Follow channels, a node's or the conversation's tree: the stored history each position asks for (the tree as it stands, for the tree from snapshot), then what is stored next, as entry, head, end and snapshot frames",
    body: subscribeRequestSchema,
    response: { status: 200, stream: subscribeFrameSchema },
  },
  getTree: {
    effect: 'read',
    method: 'get',
    path: '/conversations/{id}/tree',
    summary:
      'The tree as it stands: every node, ended ones included, and every approval waiting, with the cursor to follow the tree channel from',
    response: { status: 200, schema: treeSnapshotSchema },
  },
  queryStoredConversations: {
    effect: 'read',
    method: 'query',
    path: '/stored-conversations',
    summary: 'The kept conversations, oldest first, live or not; those a title search matches',
    body: storedConversationsQuerySchema,
    response: { status: 200, schema: storedConversationsResponseSchema },
  },
  reopenConversation: {
    effect: 'change',
    method: 'post',
    path: '/stored-conversations/{id}/reopen',
    summary: 'Bring a kept conversation back under its own id, continuing from its history',
    response: { status: 200, schema: startConversationResponseSchema },
  },
  ...SETUP_ROUTES,
  ...FOLDER_ROUTES,
  ...PUBLIC_ROUTES,
} as const satisfies Record<string, ApiRoute>;

